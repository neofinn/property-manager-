'use strict';

// The few places where SQLite and Postgres SQL differ.

const sqlite = {
  name: 'sqlite',
  idColumn: 'id INTEGER PRIMARY KEY AUTOINCREMENT',
  money: 'REAL',
  blob: 'BLOB',
  // Timestamps are stored as text "YYYY-MM-DD HH:MM:SS" (UTC) on both backends.
  now: "datetime('now')",
  like: 'LIKE',
  lower: (expr) => `${expr} COLLATE NOCASE`,
  columnsSql: (table) => ({ sql: `SELECT name FROM pragma_table_info('${table}')`, params: [] }),
  isForeignKeyError: (err) => String(err && err.message).includes('FOREIGN KEY'),
  isUniqueError: (err) => String(err && err.message).includes('UNIQUE'),
};

const postgres = {
  name: 'postgres',
  idColumn: 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
  money: 'DOUBLE PRECISION',
  blob: 'BYTEA',
  now: "to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')",
  like: 'ILIKE',
  lower: (expr) => `lower(${expr})`,
  columnsSql: (table) => ({
    sql: 'SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ?',
    params: [table],
  }),
  isForeignKeyError: (err) => err && err.code === '23503',
  isUniqueError: (err) => err && err.code === '23505',
};

module.exports = { sqlite, postgres };
